
integer_num = 10
float_num = float(integer_num)
print("Integer to float:", float_num)
print("Type:", type(float_num))

decimal_num = 10
integer_from_float = int(decimal_num)
print("Float to integer:", integer_from_float)
print("Type:", type(integer_from_float))

num_integer = 10
string_num = str(num_integer)
print("Integer to string:", string_num)
print("Type:", type(string_num))

text_num = "10"
integer_from_string = int(text_num)
print("String to integer:", integer_from_string)
print("Type:", type(integer_from_string))

integer_to_boolean = 10
boolean_value = bool(integer_to_boolean)
print("Integer to Boolean:", boolean_value)
print("Type:", type(boolean_value))